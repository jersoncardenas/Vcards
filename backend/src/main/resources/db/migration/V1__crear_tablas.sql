CREATE TABLE IF NOT EXISTS empresas (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL UNIQUE,
    foto BYTEA
);

CREATE TABLE IF NOT EXISTS usuarios (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255) NOT NULL,
    telefono VARCHAR(255) NOT NULL,
    correo VARCHAR(255) NOT NULL,
    area VARCHAR(255) NOT NULL,
    descripcion TEXT,
    foto BYTEA,
    token VARCHAR(255) NOT NULL UNIQUE,
    img_qr BYTEA,
    empresa_id INTEGER NOT NULL REFERENCES empresas(id),
    CONSTRAINT uk_usuarios_empresa_correo UNIQUE (empresa_id, correo),
    CONSTRAINT uk_usuarios_empresa_telefono UNIQUE (empresa_id, telefono)
);

CREATE INDEX IF NOT EXISTS ix_empresas_id ON empresas(id);
CREATE INDEX IF NOT EXISTS ix_usuarios_id ON usuarios(id);
